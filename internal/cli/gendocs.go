// genDocsMarker is written into every generated page. gen-docs deletes
// pages that carry it and no longer match a command, and leaves every other
// file in the directory alone.
const genDocsMarker = "<!-- generated by wayglass gen-docs; edit the command's help in internal/cli, not this file -->"

// docsOrder is the sidebar order: the order a person meets the commands on
// the golden path. Commands not listed sort after these, by name.
var docsOrder = []string{
	"wayglass", "login", "init", "agent", "agent setup",
	"intent", "intent declare", "intent list", "intent show", "intent abandon", "intent restack",
	"push", "overlaps", "propose",
	"review", "diff", "approve", "reject", "land", "sync", "publish", "why",
	"log", "watch",
	"policy", "policy test",
	"session", "session share", "session fork", "session show",
	"clone", "git-credential", "keys", "keys create", "keys list", "keys revoke",
	"project", "project delete", "doctor", "version",
}

type genDocsResult struct {
	Dir     string   `json:"dir"`
	Files   []string `json:"files"`
	Removed []string `json:"removed"`
}

func newGenDocsCmd(a *app) *cobra.Command {
	var dir string
	cmd := &cobra.Command{
		Use:   "gen-docs",
		Short: "Write the command reference as Markdown pages for the docs site",
		Long: "Writes one Markdown page per command, with Starlight frontmatter, into\n" +
			"--dir. Pages it wrote earlier for commands that no longer exist are\n" +
			"removed; other files in the directory are left alone.",
		Example: "  wayglass gen-docs --dir ../docs/src/content/docs/commands",
		Hidden:  true,
		Args:    usageArgs(cobra.NoArgs),
		RunE: func(cmd *cobra.Command, _ []string) error {
			if dir == "" {
				return UsageError("--dir is required")
			}
			res, err := genDocs(cmd.Root(), dir)
			if err != nil {
				return err
			}
			return a.output(cmd).Emit(res, func(out io.Writer) error {
				_, err := fmt.Fprintf(out, "Wrote %d pages to %s.\n", len(res.Files), res.Dir)
				return err
			})
		},
	}
	cmd.Flags().StringVar(&dir, "dir", "", "directory to write the pages into (created if missing)")
	return cmd
}

// genDocs writes a page for root and every visible command below it.
func genDocs(root *cobra.Command, dir string) (genDocsResult, error) {
	res := genDocsResult{Dir: dir, Files: []string{}, Removed: []string{}}
	if err := os.MkdirAll(dir, 0o755); err != nil { //nolint:gosec // docs output, meant to be committed
		return res, err
	}
	var cmds []*cobra.Command
	var walk func(c *cobra.Command)
	walk = func(c *cobra.Command) {
		cmds = append(cmds, c)
		for _, sub := range c.Commands() {
			if documented(sub) {
				walk(sub)
			}
		}
	}
	walk(root)

	keep := map[string]bool{}
	for _, c := range cmds {
		name := docFile(c)
		keep[name] = true
		if err := os.WriteFile(filepath.Join(dir, name), commandPage(c), 0o644); err != nil { //nolint:gosec // docs output
			return res, err
		}
		res.Files = append(res.Files, name)
	}

	entries, err := os.ReadDir(dir)
	if err != nil {
		return res, err
	}
	for _, e := range entries {
		if e.IsDir() || !strings.HasSuffix(e.Name(), ".md") || keep[e.Name()] {
			continue
		}
		p := filepath.Join(dir, e.Name())
		b, err := os.ReadFile(p) //nolint:gosec // a file in the directory we were told to write
		if err != nil {
			return res, err
		}
		if bytes.Contains(b, []byte(genDocsMarker)) {
			if err := os.Remove(p); err != nil {
				return res, err
			}
			res.Removed = append(res.Removed, e.Name())
		}
	}
	return res, nil
}

func documented(c *cobra.Command) bool {
	return c.IsAvailableCommand() && !c.IsAdditionalHelpTopicCommand() && c.Name() != "help" && c.Name() != "completion"
}

// docPath is the command path without the binary name: "intent declare".
func docPath(c *cobra.Command) string {
	if !c.HasParent() {
		return c.Name()
	}
	return strings.TrimPrefix(c.CommandPath(), c.Root().Name()+" ")
}

func docSlug(c *cobra.Command) string { return strings.ReplaceAll(docPath(c), " ", "-") }

func docFile(c *cobra.Command) string { return docSlug(c) + ".md" }

func docLink(c *cobra.Command) string { return "/commands/" + docSlug(c) + "/" }

func docOrder(c *cobra.Command) int {
	if i := slices.Index(docsOrder, docPath(c)); i >= 0 {
		return i + 1
	}
	return len(docsOrder) + 1
}

// commandPage renders one command as a Starlight page.
func commandPage(c *cobra.Command) []byte {
	var b bytes.Buffer
	p := func(format string, args ...any) { fmt.Fprintf(&b, format, args...) }

	p("---\n")
	p("title: %s\n", yamlString(c.CommandPath()))
	p("description: %s\n", yamlString(c.Short))
	p("sidebar:\n  label: %s\n  order: %d\n", yamlString(docPath(c)), docOrder(c))
	p("---\n\n")
	p("%s\n\n", genDocsMarker)

	p("%s.\n\n", mdText(strings.TrimSuffix(c.Short, ".")))
	if long := strings.TrimSpace(c.Long); long != "" {
		p("%s\n\n", helpToMarkdown(long))
	}

	group := c.HasAvailableSubCommands()
	switch {
	case group:
		p("## Usage\n\n```sh\n%s <command> [flags]\n```\n\n", c.CommandPath())
	case c.Runnable():
		p("## Usage\n\n```sh\n%s\n```\n\n", c.UseLine())
	}
	if ex := strings.TrimRight(c.Example, "\n "); ex != "" {
		p("## Examples\n\n```sh\n%s\n```\n\n", dedent(ex))
	}
	if subs := visibleSubs(c); len(subs) > 0 {
		p("## Subcommands\n\n")
		for _, s := range subs {
			p("- [`%s`](%s): %s\n", s.CommandPath(), docLink(s), mdText(s.Short))
		}
		p("\n")
	}
	if c.HasAvailableLocalFlags() {
		p("## Flags\n\n")
		flagTable(&b, c.LocalFlags())
	}
	if c.HasAvailableInheritedFlags() {
		p("## Global flags\n\n")
		flagTable(&b, c.InheritedFlags())
	}
	if !group {
		p("Exit codes and the `--json` envelope are the same for every command; see [For agents](/agents/).\n\n")
	}
	if c.HasParent() {
		parent := c.Parent()
		p("## See also\n\n- [`%s`](%s): %s\n", parent.CommandPath(), docLink(parent), mdText(parent.Short))
	}
	return append(bytes.TrimRight(b.Bytes(), "\n"), '\n')
}

func visibleSubs(c *cobra.Command) []*cobra.Command {
	var out []*cobra.Command
	for _, s := range c.Commands() {
		if documented(s) {
			out = append(out, s)
		}
	}
	slices.SortStableFunc(out, func(x, y *cobra.Command) int { return docOrder(x) - docOrder(y) })
	return out
}

func flagTable(b *bytes.Buffer, fs *pflag.FlagSet) {
	b.WriteString("| Flag | Default | Description |\n|---|---|---|\n")
	fs.VisitAll(func(f *pflag.Flag) {
		if f.Hidden || f.Name == "help" {
			return
		}
		name := "--" + f.Name
		if f.Shorthand != "" {
			name = "-" + f.Shorthand + ", " + name
		}
		if t := f.Value.Type(); t != "bool" {
			name += " " + flagArg(t)
		}
		def := ""
		if f.DefValue != "" && f.DefValue != "false" && f.DefValue != "[]" && f.DefValue != "0" {
			def = "`" + f.DefValue + "`"
		}
		usage := mdText(f.Usage)
		if strings.HasSuffix(f.Value.Type(), "Array") || strings.HasSuffix(f.Value.Type(), "Slice") {
			if !strings.Contains(usage, "repeatable") {
				usage += " (repeatable)"
			}
		}
		fmt.Fprintf(b, "| `%s` | %s | %s |\n", name, def, strings.ReplaceAll(usage, "|", "\\|"))
	})
	b.WriteString("\n")
}

func flagArg(t string) string {
	switch t {
	case "stringArray", "stringSlice", "string":
		return "string"
	case "int":
		return "int"
	case "duration":
		return "duration"
	}
	return t
}

// helpToMarkdown turns a command's Long help, hard-wrapped for a terminal,
// into Markdown: wrapped lines join into paragraphs, and lines indented by
// two spaces become a code block.
func helpToMarkdown(long string) string {
	var out []string
	for _, para := range strings.Split(long, "\n\n") {
		lines := strings.Split(para, "\n")
		if strings.HasPrefix(lines[0], "  ") {
			out = append(out, "```text\n"+dedent(para)+"\n```")
			continue
		}
		out = append(out, mdText(strings.Join(lines, " ")))
	}
	return strings.Join(out, "\n\n")
}

// dedent strips the indentation shared by every non-empty line.
func dedent(s string) string {
	lines := strings.Split(s, "\n")
	minIndent := -1
	for _, l := range lines {
		if strings.TrimSpace(l) == "" {
			continue
		}
		n := len(l) - len(strings.TrimLeft(l, " "))
		if minIndent < 0 || n < minIndent {
			minIndent = n
		}
	}
	for i, l := range lines {
		if len(l) >= minIndent && minIndent > 0 {
			lines[i] = l[minIndent:]
		}
	}
	return strings.Join(lines, "\n")
}

// mdText escapes what Markdown would read as HTML, so "<intent-id>" in help
// text shows as written.
func mdText(s string) string {
	parts := strings.Split(s, "`")
	esc := strings.NewReplacer("<", "&lt;", ">", "&gt;")
	for i := 0; i < len(parts); i += 2 { // even parts are outside code spans
		parts[i] = esc.Replace(parts[i])
	}
	return strings.Join(parts, "`")
}

func yamlString(s string) string {
	return `"` + strings.NewReplacer(`\`, `\\`, `"`, `\"`).Replace(s) + `"`
}
